function teachingBlocks(ex: Exercise): ContentBlock[] {
  const blocks: ContentBlock[] = [
    {
      type: 'teaching',
      variant: 'concept',
      title: 'حلّل قبل أن تختار',
      blocks: [
        { type: 'paragraph', text: `المعطيات: ${ex.given}` },
        { type: 'paragraph', text: `المطلوب: ${ex.required}` },
        { type: 'paragraph', text: `فكرة البداية: ${ex.idea}` },
      ],
    },
    {
      type: 'teaching',
      variant: 'why',
      title: 'اكشف الحل خطوة بخطوة',
      collapsible: true,
      revealLabel: 'حاول أولاً، ثم اكشف التحليل والحل',
      blocks: [
        { type: 'paragraph', text: `القاعدة: ${ex.rule}` },
        { type: 'paragraph', text: `لماذا تنطبق؟ ${ex.why}` },
        { type: 'list', ordered: true, items: ex.steps },
        {
          type: 'callout',
          variant: 'note',
          title: 'النتيجة',
          blocks: [{ type: 'paragraph', text: ex.result }],
        },
        {
          type: 'callout',
          variant: 'hint',
          title: 'تحقّق',
          blocks: [{ type: 'paragraph', text: ex.verify }],
        },
        ...(ex.warning
          ? [
              {
                type: 'teaching' as const,
                variant: 'pitfall',
                title: 'انتبه',
                blocks: [{ type: 'paragraph' as const, text: ex.warning }],
              },
            ]
          : []),
      ],
    },
  ];
  return blocks;
}

