import type { ContentBlock, LessonStepInput } from '../schema';

export const p = (text: string): ContentBlock => ({ type: 'paragraph', text });
export function reasoning(title: string, ...paragraphs: string[]): ContentBlock {
  return { type: 'teaching', variant: 'why', title, blocks: paragraphs.map(p) };
}
export function lesson01Figure(mode: string, page: number, alt: string): ContentBlock {
  return {
    type: 'figure',
    diagram: {
      kind: 'interactive',
      origin: 'authored',
      id: `l1-${mode}`,
      renderer: 'lesson-one-lab',
      alt,
      caption: 'رسم تعليمي من إعداد المنصّة، مبني على معطيات السؤال؛ ليس صورة من الكتاب.',
      source: { page },
      params: { mode },
    },
  };
}

