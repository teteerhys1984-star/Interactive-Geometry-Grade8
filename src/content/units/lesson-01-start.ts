function choiceStep(indexes: number[], id: string, title: string): LessonStepInput {
  return {
    id,
    title,
    kicker: 'انطلاقة نشطة',
    source: { page: launchChoices[indexes[0]!]!.page, locator: 'السؤال 1' },
    blocks: [
      p('في كل مما يلي، واحدة فقط من الإجابات الثلاث ① و ② و ③ المقترحة صحيحة، أشر إليها:'),
      ...indexes.flatMap((index): ContentBlock[] => {
        const q = launchChoices[index]!;
        return [
          { type: 'questionGroup', items: [{ label: `${index + 1}`, text: q.question }] },
          { type: 'list', ordered: true, items: q.options },
          ...(index === 2
            ? [
                lesson01Figure(
                  'area',
                  3,
                  'متوازي أضلاع قاعدته خمسة وارتفاعه ثلاثة وضلعُه المائل أربعة سنتيمترات',
                ),
              ]
            : []),
          ...(index === 5
            ? [lesson01Figure('diagonals', 3, 'القطعتان متناصفتان مع تمييز علامة كل قطر')]
            : []),
          reasoning(`حلّ ${index + 1} — الفكرة ثم التحقّق`, ...q.solution),
        ];
      }),
    ],
  };
}

