const solutions: NonNullable<TeacherResourcesInput['textbookSolutions']> = [];
let answerIndex = 0;
for (const step of lesson01TeacherSteps) {
  const figures = step.blocks.filter((b) => b.type === 'figure');
  const group = step.blocks.find((b) => b.type === 'questionGroup');
  const questions =
    group?.type === 'questionGroup'
      ? group.items.map((i) => i.text)
      : step.blocks
          .filter((b) => b.type === 'paragraph')
          .map((b) => (b.type === 'paragraph' ? b.text : ''))
          .slice(-1);
  questions.forEach((question, i) => {
    const blocks: ContentBlock[] = [
      ...step.blocks.filter((b) => b.type === 'callout'),
      ...figures,
      reasoning('حلول المعلّم — الفكرة والخطوات والتحقّق', ...answers[answerIndex]!),
    ];
    solutions.push({
      id: `l1-teacher-${++answerIndex}`,
      reference: `صفحة ${step.source!.page} — ${step.kicker} — ${step.title} — ${i + 1}`,
      question,
      blocks,
    });
  });
}
