function sourceFigureBlock(exercise: FinalExercise): ContentBlock[] {
  const figure = exercise.sourceFigure;
  if (!figure) return [];
  if (figure.type === 'reference') {
    return [
      {
        type: 'figure',
        diagram: {
          kind: 'reference',
          origin: 'textbook',
          id: figure.id,
          alt: figure.alt,
          caption: figure.caption,
          source: exercise.source,
          reason: figure.reason,
        },
      },
    ];
  }
  return [
    {
      type: 'figure',
      diagram: {
        kind: 'interactive',
        origin: 'textbook',
        id: figure.id,
        renderer: 'unit-final-figure',
        alt: figure.alt,
        caption: figure.caption,
        source: exercise.source,
        params: { scenario: figure.scenario },
      },
    },
  ];
}

